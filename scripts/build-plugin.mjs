#!/usr/bin/env node
// Build the agent plugin's server: one self-contained ES module, dependencies inlined, so a plugin
// installed from git (Claude Code, Codex, ChatGPT desktop) runs with `node` alone: no npm install,
// no node_modules. Committed, like src/apps/generated/runtime.ts, and checked for drift in tests.
//
//   node scripts/build-plugin.mjs           write plugin/server/azure-mcp.mjs
//   node scripts/build-plugin.mjs --check   exit 1 if it is out of date
import { build } from "esbuild";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "plugin", "server", "azure-mcp.mjs");
const check = process.argv.includes("--check");

const result = await build({
  entryPoints: [join(ROOT, "dist", "index.js")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  write: false,
  legalComments: "inline",
  // Some dependencies are CommonJS and call require(); give the ESM bundle one.
  banner: { js: "import { createRequire as __azureCreateRequire } from 'node:module'; const require = __azureCreateRequire(import.meta.url);" },
});
// The entry's shebang has to stay on line 1, so the generated-file note goes after it.
const text = result.outputFiles[0].text.replace(/^#!.*\n/, "");
const code = `#!/usr/bin/env node\n// GENERATED by scripts/build-plugin.mjs from dist/index.js. Do not edit.\n${text}`;
const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
if (current === code) {
  console.error("build-plugin: plugin/server/azure-mcp.mjs is current");
} else if (check) {
  console.error("build-plugin: plugin/server/azure-mcp.mjs is out of date; run `npm run plugin:build`");
  process.exit(1);
} else {
  writeFileSync(OUT, code);
  console.error(`build-plugin: wrote plugin/server/azure-mcp.mjs (${(code.length / 1024).toFixed(0)} KB)`);
}
if (!check) copyFileSync(join(ROOT, "assets", "azure-512.png"), join(ROOT, "plugin", "assets", "azure-512.png"));
